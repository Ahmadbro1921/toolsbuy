import { AIProviderAdapter, AIGenerateMetadataInput, AIGeneratedMetadataOutput } from "./types";

export class GeminiProvider implements AIProviderAdapter {
  name: "gemini" = "gemini";
  private apiKey: string;
  private model: string;

  constructor(apiKey?: string, model?: string) {
    this.apiKey = apiKey || process.env.AI_API_KEY || "";
    this.model = model || process.env.AI_MODEL_NAME || "gemini-1.5-flash";
  }

  isConfigured(): boolean {
    return Boolean(this.apiKey && this.apiKey.trim().length > 10);
  }

  async testConnection(): Promise<{ success: boolean; message: string; latencyMs?: number }> {
    if (!this.isConfigured()) {
      return { success: false, message: "Gemini API key is not configured in environment or settings." };
    }

    const start = Date.now();
    try {
      const response = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/${this.model}:generateContent?key=${this.apiKey}`,
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            contents: [{ parts: [{ text: "Respond with the word 'OK' if you receive this ping." }] }],
          }),
          signal: AbortSignal.timeout(8000),
        }
      );

      const latencyMs = Date.now() - start;

      if (!response.ok) {
        const errorData = await response.json().catch(() => ({}));
        const errMessage = errorData?.error?.message || response.statusText;
        return { success: false, message: `Gemini API error (${response.status}): ${errMessage}`, latencyMs };
      }

      return { success: true, message: `Connected to Gemini (${this.model}) successfully.`, latencyMs };
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      return { success: false, message: `Gemini connection failed: ${msg}`, latencyMs: Date.now() - start };
    }
  }

  async generateToolMetadata(input: AIGenerateMetadataInput): Promise<AIGeneratedMetadataOutput> {
    if (!this.isConfigured()) {
      throw new Error("Gemini AI API key is not configured. Please configure it in Admin Settings.");
    }

    const prompt = `
You are a senior AI market analyst and technical directory curator.
Analyze the following AI tool and generate structured metadata in strict JSON format.

Tool Name: "${input.toolName}"
Official Website: "${input.websiteUrl}"
${input.categoryHint ? `User Category Hint: "${input.categoryHint}"` : ""}
${input.rawText ? `Extracted Context / Features:\n${input.rawText}` : ""}

Return ONLY a valid JSON object matching this schema:
{
  "description": "Engaging, objective 2-3 sentence overview of what the tool accomplishes and who it is for.",
  "suggestedCategory": "One of: Text & LLMs, Image & Art, Code & Dev, Audio & Speech, Video Generation, Productivity, Research & Data",
  "tags": ["3 to 6 concise technical tags"],
  "features": ["3 to 5 core features"],
  "useCases": ["2 to 4 practical real-world use cases"],
  "seoTitle": "SEO title under 60 characters",
  "seoDescription": "Meta description under 155 characters",
  "confidenceScore": 0.95
}
`;

    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/${this.model}:generateContent?key=${this.apiKey}`,
      {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: {
            temperature: 0.2,
            responseMimeType: "application/json",
          },
        }),
        signal: AbortSignal.timeout(15000),
      }
    );

    if (!response.ok) {
      const err = await response.json().catch(() => ({}));
      throw new Error(`Gemini generation failed (${response.status}): ${err?.error?.message || response.statusText}`);
    }

    const data = await response.json();
    const rawContent = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!rawContent) {
      throw new Error("No response content generated by Gemini.");
    }

    const parsed = JSON.parse(rawContent);
    return {
      description: parsed.description || "A powerful AI tool engineered for modern workflows.",
      suggestedCategory: parsed.suggestedCategory || "Productivity",
      tags: Array.isArray(parsed.tags) ? parsed.tags : ["AI", "Productivity"],
      features: Array.isArray(parsed.features) ? parsed.features : ["Automated workflow"],
      useCases: Array.isArray(parsed.useCases) ? parsed.useCases : ["Professional tasks"],
      seoTitle: parsed.seoTitle || `${input.toolName} — AI Directory Review`,
      seoDescription: parsed.seoDescription || parsed.description?.slice(0, 150) || "",
      confidenceScore: typeof parsed.confidenceScore === "number" ? parsed.confidenceScore : 0.9,
    };
  }
}
